"use strict";
// Real Chromium UI; all provider/model data comes from an isolated offline fixture.
const fs = require("node:fs");
const path = require("node:path");
const {spawn} = require("node:child_process");
const assert = require("node:assert/strict");
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const root = path.resolve(__dirname, "..");
const output = path.join(root, "output", "research-journey-acceptance", `${Date.now()}-${require("node:crypto").randomBytes(3).toString("hex")}`);
fs.mkdirSync(output, {recursive:true});
const server = spawn(path.join(root, "webapp/.venv/Scripts/python.exe"), ["-X", "utf8", "-B", path.join(__dirname, "research_journey_acceptance_server.py"), "--output", output], {cwd:root, windowsHide:true, stdio:["ignore","pipe","pipe"]});
let logs="";server.stdout.on("data",b=>logs+=b);server.stderr.on("data",b=>logs+=b);
const errors=[];let browser;
async function run(){
  const identity=path.join(output,"SERVER.json");
  for(let i=0;i<150&&!fs.existsSync(identity);i++){
    if(server.exitCode!==null)throw new Error("Fixture server exited: "+logs);
    await new Promise(resolve=>setTimeout(resolve,100));
  }
  assert.ok(fs.existsSync(identity),"Isolated server starts");
  const {base}=JSON.parse(fs.readFileSync(identity,"utf8"));
  browser=await chromium.launch({channel:"chrome",headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
  browser.qaPage=page;
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(()=>!document.querySelector("#intake-model-notice").textContent.includes("正在读取"));
  await page.locator("#initial-idea").fill("[QA 合成验收] 我想研究随机低秩逼近，在个人电脑上比较误差和计算预算。");
  await page.locator("#planning-mode").selectOption("demo");
  await page.locator("#create-button").click();
  await page.locator(".research-journey").waitFor();
  assert.equal(await page.locator(".journey-stages>li").count(),5);
  await page.locator('[data-action="journey-read"]').first().click();
  await page.locator("#reference-input").fill("10.1137/090771806");
  await page.locator('#reference-import-form button[type="submit"]').click();
  await page.locator(".imported-metadata").waitFor();
  await page.locator('[data-action="prepare-abstract-note"]').click();
  assert.equal(await page.locator('.reading-note-form [name="confirmed"]').isChecked(),false);
  await page.locator('.reading-note-form [name="confirmed"]').check();
  await page.locator('.reading-note-form button[type="submit"]').click();
  await page.locator(".reading-note").waitFor();
  await page.locator('[data-action="return-research"]').first().click();
  await page.locator(".research-actions>summary").click();
  await page.locator('[data-action="research-plan-create"]').click();
  await page.locator('[data-action="research-action-run"][data-action-id="search-1"]').waitFor();
  await page.locator('[data-action="research-action-run"][data-action-id="search-1"]').click();
  await page.waitForFunction(()=>document.querySelector(".research-action-list")?.textContent.includes("已返回题录"));
  await page.locator('[data-action="research-action-run"][data-action-id="revise"]').click();
  await page.locator('[data-action="direction-accept"]').waitFor();
  assert.ok((await page.locator(".proposal-diff").textContent()).includes("QA 合成修订"));
  const addBanner=()=>{const el=document.createElement("div");el.textContent="离线浏览器验收：题录及模型均为合成数据，未调用真实模型";el.style.cssText="position:fixed;bottom:0;left:0;right:0;background:#fff4d5;color:#58471b;padding:6px;text-align:center;z-index:9999;font-size:12px";document.body.append(el);};
  await page.evaluate(addBanner);
  await page.locator(".research-journey").screenshot({path:path.join(output,"desktop-actions.png")});
  await page.locator('[data-action="direction-accept"]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-action="direction-accept"]'));
  await page.locator('[data-action="journey-compare"]').first().click();
  await page.locator("#selection-reason").fill("QA：依据已确认的摘录，先验证公平预算下的误差。");
  await page.locator('[data-action="select"]').first().click();
  await page.locator('[data-action="download-decision-package"]').first().waitFor();
  const downloadPromise=page.waitForEvent("download");
  await page.locator('[data-action="download-decision-package"]').first().click();
  const download=await downloadPromise;await download.saveAs(path.join(output,"decision-package.md"));
  const content=fs.readFileSync(path.join(output,"decision-package.md"),"utf8");
  assert.ok(content.includes("本轮行动与人工确认"));assert.ok(content.includes("不是全文指纹"));
  await page.reload();await page.locator(".research-journey").waitFor();
  assert.ok((await page.locator(".journey-stages").textContent()).includes("1 条已确认笔记"));
  const audit=await(await page.request.get(base+"/__research_qa__")).json();
  assert.equal(audit.import_operations,1);assert.equal(audit.search_operations,1);assert.equal(audit.model_operations,1);assert.equal(audit.model_network_calls,0);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(addBanner);await page.locator(".research-journey").scrollIntoViewIfNeeded();
  const overflow=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,elements:[...document.querySelectorAll("body *")].filter(el=>el.getClientRects().length&&el.getBoundingClientRect().right>innerWidth+1).map(el=>({tag:el.tagName,id:el.id,class:typeof el.className==="string"?el.className:"",parent:el.parentElement?.className,text:el.textContent.slice(0,250),width:el.getBoundingClientRect().width,right:el.getBoundingClientRect().right})).slice(0,40)}));
  fs.writeFileSync(path.join(output,"mobile-layout.json"),JSON.stringify(overflow,null,2));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"390px page has no horizontal overflow");
  await page.screenshot({path:path.join(output,"mobile-journey.png")});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(output,"validation.json"),JSON.stringify({status:"passed",fixture:"synthetic_offline",checks:["five phases","exact import","unconfirmed abstract draft","reading confirmation","single-step search","evidence revision preview","explicit accept","selection","actual Markdown download","refresh recovery","390px overflow","no browser errors"],audit},null,2));
  console.log(JSON.stringify({status:"passed",output,audit}));
}
run().catch(async error=>{fs.writeFileSync(path.join(output,"failure.txt"),error.stack+"\n"+logs);if(browser?.qaPage)await browser.qaPage.screenshot({path:path.join(output,"failure.png")}).catch(()=>{});console.error(error.stack);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill();fs.writeFileSync(path.join(output,"server.log"),logs);});
